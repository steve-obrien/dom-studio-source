/**
 * Social post templates.
 *
 * A template is a small JSON file: a frame size, a background and a list of
 * text, shape and image layers with only the fields that differ from the
 * defaults. Templates are written by people or generated by a model (see
 * scripts/generate-social-templates.mjs), so every template goes through
 * `templateToPoster`, which keeps known fields only, clamps numbers, accepts
 * plain colours and safe image URLs, and fills in the rest. Whatever a model
 * returns, the editor receives an ordinary poster.
 *
 * Every field maps onto a property the poster inspector edits, including
 * gradients, borders, shadows, backdrop blur and image filters, so a design
 * made in the studio saves as a template (`posterToTemplate`) and opens again
 * unchanged.
 */

export const templateIndustries = [
	{ value: 'restaurant', label: 'Restaurant & café' },
	{ value: 'real-estate', label: 'Real estate' },
	{ value: 'fitness', label: 'Fitness' },
	{ value: 'retail', label: 'Retail & fashion' },
	{ value: 'saas', label: 'Software' },
	{ value: 'events', label: 'Events' },
	{ value: 'beauty', label: 'Beauty & wellness' },
	{ value: 'travel', label: 'Travel' },
];
export const templateKinds = [
	{ value: 'offer', label: 'Offer' },
	{ value: 'announcement', label: 'Announcement' },
	{ value: 'event', label: 'Event' },
	{ value: 'testimonial', label: 'Testimonial' },
	{ value: 'listing', label: 'Listing' },
];
export const templateFonts = { condensed: fontOptions[0].value, sans: fontOptions[1].value, serif: fontOptions[2].value, mono: fontOptions[3].value };

const maxLayers = 24;
const plainColour = /^(#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})|transparent|(rgb|rgba|hsl|hsla)\(\s*[-\d.%\s,/]+\))$/i;

function clamp(value, min, max, fallback) {
	const number = Number(value);
	return Number.isFinite(number) ? Math.min(max, Math.max(min, number)) : fallback;
}
/** Hex, rgb() and hsl() colours with numbers only, so nothing else reaches the CSS. */
function colour(value, fallback) {
	return typeof value === 'string' && plainColour.test(value.trim()) ? value.trim() : fallback;
}
function list(value, max) {
	return Array.isArray(value) ? value.slice(0, max) : [];
}
function cleanFill(raw = {}) {
	return createFill({
		kind: oneOf(raw.kind, ['solid', 'linear', 'radial'], 'solid'),
		color: colour(raw.color, '#171717'), alpha: clamp(raw.alpha, 0, 100, 100),
		gradientFrom: colour(raw.gradientFrom, '#171717'), gradientFromAlpha: clamp(raw.gradientFromAlpha, 0, 100, 100),
		gradientTo: colour(raw.gradientTo, '#4f46e5'), gradientToAlpha: clamp(raw.gradientToAlpha, 0, 100, 100),
		gradientAngle: clamp(raw.gradientAngle, -360, 360, 135), gradientFromStop: clamp(raw.gradientFromStop, 0, 100, 0), gradientToStop: clamp(raw.gradientToStop, 0, 100, 100),
	});
}
function cleanShadow(raw = {}) {
	return createShadow({
		kind: oneOf(raw.kind, ['drop', 'inset', 'ring'], 'drop'), color: colour(raw.color, '#000000'), alpha: clamp(raw.alpha, 0, 100, 20),
		x: clamp(raw.x, -500, 500, 0), y: clamp(raw.y, -500, 500, 8), blur: clamp(raw.blur, 0, 500, 18), spread: clamp(raw.spread, -500, 500, 0),
	});
}
function oneOf(value, options, fallback) {
	const values = options.map((option) => (typeof option === 'string' ? option : option.value));
	return values.includes(value) ? value : fallback;
}
function text(value, max = 400) {
	return typeof value === 'string' ? value.slice(0, max) : '';
}

/**
 * One template layer as a complete poster layer.
 *
 * @param {object} raw Template layer.
 * @param {number} index Position, used for the id.
 * @param {{ width: number, height: number }} frame Frame size.
 * @returns {object|null} Poster layer, or null when the layer is unusable.
 */
export function templateLayer(raw, index, frame) {
	if (!raw || !['text', 'shape', 'image'].includes(raw.type)) return null;
	const value = raw.type === 'image' ? safePosterImage(String(raw.value || '')) : text(raw.value);
	if (raw.type === 'image' && !value) return null;
	const span = Math.max(frame.width, frame.height);
	return createPosterLayer(raw.type, `layer-${index + 1}`, {
		name: text(raw.name, 60) || (raw.type === 'text' ? value.split('\n')[0].slice(0, 40) || 'Text' : raw.type === 'image' ? 'Image' : 'Shape'),
		value,
		x: Math.round(clamp(raw.x, -span, span * 2, 0)),
		y: Math.round(clamp(raw.y, -span, span * 2, 0)),
		width: Math.round(clamp(raw.width, 16, span * 2, 200)),
		height: Math.round(clamp(raw.height, 16, span * 2, 100)),
		pinX: oneOf(raw.pinX, pinXOptions, 'auto'),
		pinY: oneOf(raw.pinY, pinYOptions, 'auto'),
		fill: colour(raw.fill, raw.type === 'shape' ? '#e5e5e5' : 'transparent'),
		color: colour(raw.color, '#171717'),
		fontFamily: templateFonts[raw.font] || templateFonts.sans,
		fontSize: clamp(raw.fontSize, 8, 500, 48),
		fontWeight: oneOf(String(raw.fontWeight ?? '400'), ['400', '700', '900'], '400'),
		lineHeight: clamp(raw.lineHeight, 0.5, 3, 1.2),
		letterSpacing: clamp(raw.letterSpacing, -20, 100, 0),
		textAlign: oneOf(raw.textAlign, ['left', 'center', 'right'], 'left'),
		textTransform: oneOf(raw.textTransform, ['none', 'uppercase', 'lowercase', 'capitalize'], 'none'),
		radius: clamp(raw.radius, 0, 1000, 0),
		opacity: clamp(raw.opacity, 0, 100, 100),
		objectFit: oneOf(raw.objectFit, ['cover', 'contain', 'fill'], 'cover'),
		objectY: clamp(raw.objectY, 0, 100, 50),
		brightness: clamp(raw.brightness, 0, 200, 100),
		saturation: clamp(raw.saturation, 0, 200, 100),
		blur: clamp(raw.blur, 0, 40, 0),
		sepia: clamp(raw.sepia, 0, 100, 0),
		background: createBackgroundState({ fills: list(raw.gradient, 6).map(cleanFill) }, { allowEmpty: true }),
		backdrop: raw.backdrop ? createBackdrop({ enabled: true, blur: clamp(raw.backdrop.blur, 0, 200, 0), saturate: clamp(raw.backdrop.saturate, 0, 5, 1) }) : createBackdrop(),
		border: raw.border ? createDesignerBorder({ enabled: true, width: clamp(raw.border.width, 0, 200, 1), style: oneOf(raw.border.style, ['solid', 'dashed', 'dotted', 'double'], 'solid'), color: colour(raw.border.color, '#171717') }) : createDesignerBorder({ enabled: false }),
		shadows: list(raw.shadows, 6).map(cleanShadow),
		locked: raw.locked === true,
	});
}

/**
 * Converts a template to a poster the studio can open.
 *
 * @param {object} raw Template JSON.
 * @returns {object} Poster.
 */
export function templateToPoster(raw = {}) {
	const frame = { width: Math.round(clamp(raw.width, 200, 4000, 1080)), height: Math.round(clamp(raw.height, 200, 4000, 1350)) };
	const layers = (Array.isArray(raw.layers) ? raw.layers : []).slice(0, maxLayers).map((layer, index) => templateLayer(layer, index, frame)).filter(Boolean);
	return { version: 1, title: text(raw.title, 120) || 'Untitled post', ...frame, background: colour(raw.background, '#ffffff'), layers };
}

const fontKeys = Object.fromEntries(Object.entries(templateFonts).map(([key, value]) => [value, key]));
const fillFields = ['kind', 'color', 'alpha', 'gradientFrom', 'gradientFromAlpha', 'gradientTo', 'gradientToAlpha', 'gradientAngle', 'gradientFromStop', 'gradientToStop'];
const shadowFields = ['kind', 'color', 'alpha', 'x', 'y', 'blur', 'spread'];
const pick = (source, keys) => Object.fromEntries(keys.map((key) => [key, source[key]]));

/**
 * Saves a poster as a template, the inverse of `templateToPoster`. Hidden
 * layers are left out, and only the fields that apply to each layer kind and
 * differ from the defaults are written, so the file stays readable.
 *
 * @param {object} poster Poster model.
 * @param {{ id?: string, industry?: string, kind?: string }} [meta] Gallery fields.
 * @returns {object} Template JSON.
 */
export function posterToTemplate(poster, meta = {}) {
	const layers = poster.layers.filter((layer) => !layer.hidden).map((layer) => {
		const out = { type: layer.type, name: layer.name };
		if (layer.value) out.value = layer.value;
		Object.assign(out, { x: layer.x, y: layer.y, width: layer.width, height: layer.height });
		const fields = {
			pinX: [layer.pinX, 'auto'], pinY: [layer.pinY, 'auto'], opacity: [layer.opacity, 100], radius: [layer.radius, 0], locked: [layer.locked, false],
			...(layer.type === 'image'
				? { objectFit: [layer.objectFit, 'cover'], objectY: [layer.objectY, 50], brightness: [layer.brightness, 100], saturation: [layer.saturation, 100], blur: [layer.blur, 0], sepia: [layer.sepia, 0] }
				: { fill: [layer.fill, layer.type === 'shape' ? undefined : 'transparent'] }),
			...(layer.type === 'text'
				? { font: [fontKeys[layer.fontFamily] || 'sans', undefined], fontSize: [layer.fontSize, undefined], fontWeight: [layer.fontWeight, '400'], lineHeight: [layer.lineHeight, 1.2], letterSpacing: [layer.letterSpacing, 0], textAlign: [layer.textAlign, 'left'], textTransform: [layer.textTransform, 'none'], color: [layer.color, undefined] }
				: {}),
		};
		for (const [key, [value, fallback]] of Object.entries(fields)) if (value !== fallback) out[key] = value;
		if (layer.type !== 'image' && layer.background?.enabled && layer.background.fills?.some((fill) => fill.enabled)) out.gradient = layer.background.fills.filter((fill) => fill.enabled).map((fill) => pick(fill, fillFields));
		if (layer.type !== 'image' && layer.backdrop?.enabled) out.backdrop = { blur: layer.backdrop.blur, saturate: layer.backdrop.saturate };
		if (layer.border?.enabled && layer.border.style !== 'none') out.border = { width: layer.border.width, style: layer.border.style, color: layer.border.color };
		const shadows = (layer.shadows || []).filter((shadow) => shadow.enabled);
		if (shadows.length) out.shadows = shadows.map((shadow) => pick(shadow, shadowFields));
		return out;
	});
	const id = meta.id || poster.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'post';
	return { id, title: poster.title, industry: meta.industry || 'other', kind: meta.kind || 'announcement', source: 'designer', width: poster.width, height: poster.height, background: poster.background, layers };
}

/**
 * Saved templates, kept through a designer storage adapter (`core/storage.js`):
 * the browser for the demo, or the host app's API and database through
 * `createHttpStorage`. Saving always creates a new template with an unused id,
 * so a built-in or earlier template is never overwritten.
 *
 * @param {object} adapter Storage adapter with `load`, `save` and `list`.
 * @returns {{ list: () => Promise<Array<object>>, saveAs: (poster: object, meta?: object, reserved?: Array<string>) => Promise<string> }}
 */
export function createTemplateLibrary(adapter) {
	return {
		async list() {
			const items = await adapter.list();
			const values = await Promise.all(items.map((item) => adapter.load(item.id)));
			return loadTemplates(values.map((value, index) => value && { ...value, id: items[index].id }).filter(Boolean));
		},
		async saveAs(poster, meta = {}, reserved = []) {
			const template = posterToTemplate(poster, meta);
			const taken = new Set([...reserved, ...(await adapter.list()).map((item) => item.id)]);
			let id = template.id;
			for (let copy = 2; taken.has(id); copy += 1) id = `${template.id}-${copy}`;
			await adapter.save(id, { ...template, id });
			return id;
		},
	};
}

/**
 * Sorts templates and attaches their posters, dropping any without layers.
 *
 * @param {Array<object>} list Template JSON files.
 * @returns {Array<object>} `{ id, title, industry, kind, poster }`.
 */
export function loadTemplates(list) {
	return list
		.map((raw) => ({ id: text(raw.id, 80), title: text(raw.title, 120), industry: oneOf(raw.industry, templateIndustries, 'other'), kind: oneOf(raw.kind, templateKinds, 'announcement'), poster: templateToPoster(raw) }))
		.filter((template) => template.id && template.poster.layers.length)
		.sort((a, b) => a.industry.localeCompare(b.industry) || a.title.localeCompare(b.title));
}

/**
 * Operations that replace a poster document's content with a template, as
 * one undoable step. The template is resized to the document's current
 * format first, so picking a template keeps the format you are editing.
 *
 * @param {object} doc Poster document.
 * @param {object} poster Template poster from `templateToPoster`.
 * @returns {{ operations: Array<object>, firstId: string }} Operations, and the id of the front text layer to select.
 */
export function templateOperations(doc, poster) {
	const frame = doc.nodes[doc.rootId];
	const sized = resizePoster(poster, { width: frame.props.width, height: frame.props.height });
	const removals = frame.children.toReversed().map((id) => ({ op: 'remove', id }));
	const inserts = sized.layers.map((layer, index) => {
		const fragment = fromTree({ ...layerToTree(layer), id: undefined }, { parent: frame.id });
		return { op: 'insert', parent: frame.id, index, fragment };
	});
	const fields = [['title', sized.title], ['background', sized.background]].map(([key, value]) => ({ op: 'setProp', id: frame.id, key, value }));
	const text = inserts.filter(({ fragment }) => fragment.nodes[fragment.rootId].type === 'poster:text');
	return { operations: [...removals, ...fields, ...inserts], firstId: text[0]?.fragment.rootId || '' };
}

/**
 * JSON schema for a generated template, used with structured output so the
 * model can only return the fields `templateToPoster` reads.
 */
export function templateJsonSchema() {
	const number = { type: 'number' };
	const layer = {
		type: 'object',
		additionalProperties: false,
		required: ['type', 'name', 'value', 'x', 'y', 'width', 'height', 'fill', 'color', 'font', 'fontSize', 'fontWeight', 'lineHeight', 'letterSpacing', 'textAlign', 'textTransform', 'radius', 'opacity', 'pinX', 'pinY'],
		properties: {
			type: { type: 'string', enum: ['text', 'shape'] },
			name: { type: 'string' },
			value: { type: 'string' },
			x: number, y: number, width: number, height: number,
			fill: { type: 'string', pattern: '^#[0-9a-fA-F]{6}$' },
			color: { type: 'string', pattern: '^#[0-9a-fA-F]{6}$' },
			font: { type: 'string', enum: Object.keys(templateFonts) },
			fontSize: number,
			fontWeight: { type: 'string', enum: ['400', '700', '900'] },
			lineHeight: number,
			letterSpacing: number,
			textAlign: { type: 'string', enum: ['left', 'center', 'right'] },
			textTransform: { type: 'string', enum: ['none', 'uppercase'] },
			radius: number,
			opacity: number,
			pinX: { type: 'string', enum: pinXOptions.map((option) => option.value) },
			pinY: { type: 'string', enum: pinYOptions.map((option) => option.value) },
		},
	};
	return {
		type: 'object',
		additionalProperties: false,
		required: ['title', 'width', 'height', 'background', 'layers'],
		properties: {
			title: { type: 'string' },
			width: { type: 'number', enum: [1080] },
			height: { type: 'number', enum: [1350] },
			background: { type: 'string', pattern: '^#[0-9a-fA-F]{6}$' },
			layers: { type: 'array', items: layer },
		},
	};
}
