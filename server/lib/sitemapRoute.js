import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { loadDatabaseBlogRoutes, loadStaticRouteRecords, mergeRouteRecords } from '../../scripts/lib/load-routes.mjs';
import { buildSitemap, readSiteUrl } from '../../scripts/lib/sitemap.mjs';

/**
 * Registers the live public sitemap endpoint before static files and SSR fallbacks.
 *
 * @param {import('express').Express} app Express application.
 * @param {{ loadRouteRecords?: Function, loadSiteUrl?: Function }} [options] Optional loader overrides for testing.
 * @returns {void}
 */
export function installSitemapRoute(app, options = {}) {
	app.get('/sitemap.xml', createSitemapHandler(options));
}

/**
 * Creates a sitemap request handler with injectable data loaders.
 *
 * @param {{ loadRouteRecords?: Function, loadSiteUrl?: Function }} [options] Optional loader overrides.
 * @returns {import('express').RequestHandler} Express sitemap request handler.
 */
export function createSitemapHandler({
	loadRouteRecords = createSitemapRouteLoader(),
	loadSiteUrl = readSiteUrl,
} = {}) {
	/**
	 * Builds the sitemap from current application routes and persisted articles.
	 *
	 * @param {import('express').Request} request Incoming request.
	 * @param {import('express').Response} response Outgoing response.
	 * @returns {Promise<void>}
	 */
	return async function handleSitemapRequest(request, response) {
		try {
			const [siteUrl, routeRecords] = await Promise.all([
				loadSiteUrl(),
				loadRouteRecords(),
			]);
			response
				.status(200)
				.set({
					'Cache-Control': 'no-cache, no-store, must-revalidate',
					'Content-Type': 'application/xml; charset=utf-8',
					'X-Content-Type-Options': 'nosniff',
				})
				.send(buildSitemap(siteUrl, routeRecords));
		} catch (error) {
			console.error('Unable to build the dynamic sitemap.', error);
			response
				.status(503)
				.set({
					'Cache-Control': 'no-store',
					'Content-Type': 'text/plain; charset=utf-8',
				})
				.send('Sitemap temporarily unavailable.');
		}
	};
}

/**
 * Creates a route loader that reuses the deployed source inventory in production
 * and refreshes database articles on every request. Development continues to
 * discover local edits without requiring a rebuild.
 *
 * @param {object} [options] Runtime mode and injectable data sources.
 * @param {boolean} [options.production] Whether to require the deployment inventory.
 * @param {string} [options.manifestPath] Generated source route inventory path.
 * @param {Function} [options.loadSourceRoutes] Development source discovery loader.
 * @param {Function} [options.loadArticleRoutes] Current database article loader.
 * @returns {() => Promise<Array<{ path: string, lastmod?: string }>>} Public route loader.
 */
export function createSitemapRouteLoader({
	production = process.env.NODE_ENV === 'production',
	manifestPath = path.join(process.cwd(), 'dist', 'server', 'sitemap-routes.json'),
	loadSourceRoutes = loadStaticRouteRecords,
	loadArticleRoutes = loadDatabaseBlogRoutes,
} = {}) {
	let sourceRecordsPromise;

	/**
	 * Shares a successful deployment-inventory read between requests while allowing
	 * a later request to retry if the artifact was missing or invalid.
	 *
	 * @returns {Promise<Array<{ path: string, lastmod?: string }>>} Source route records.
	 */
	async function loadSourceRecords() {
		if (!production) return loadSourceRoutes({ throwOnError: true, includeDatabaseBlog: false });
		try {
			sourceRecordsPromise ??= readBuiltRouteRecords(manifestPath);
			return await sourceRecordsPromise;
		} catch (error) {
			sourceRecordsPromise = undefined;
			throw error;
		}
	}

	/**
	 * Combines deployment-owned pages with the current database article inventory,
	 * retaining the newest known date for slugs that also have local Markdown.
	 *
	 * @returns {Promise<Array<{ path: string, lastmod?: string }>>} Current public routes.
	 */
	return async function loadCurrentRouteRecords() {
		const [sourceRecords, articleRecords] = await Promise.all([
			loadSourceRecords(),
			loadArticleRoutes({ throwOnError: true }),
		]);
		return mergeRouteRecords([...sourceRecords, ...articleRecords]);
	};
}

/**
 * Reads the source route inventory generated by the build. Production fails
 * visibly when the artifact is incomplete instead of scanning the source tree.
 *
 * @param {string} manifestPath Generated inventory path.
 * @returns {Promise<Array<{ path: string, lastmod?: string }>>} Deployed source routes.
 */
async function readBuiltRouteRecords(manifestPath) {
	const records = JSON.parse(await readFile(manifestPath, 'utf8'));
	if (!Array.isArray(records) || !records.length || !records.every(isBuiltRouteRecord)) {
		throw new Error('Invalid sitemap route inventory. Run npm run seo:generate before starting production.');
	}
	return records;
}

/**
 * Validates the minimal source record contract before caching a build artifact.
 *
 * @param {unknown} record Parsed inventory entry.
 * @returns {boolean} Whether the record contains a route and an optional valid date.
 */
function isBuiltRouteRecord(record) {
	return record !== null
		&& typeof record === 'object'
		&& typeof record.path === 'string'
		&& record.path.startsWith('/')
		&& (record.lastmod === undefined || (typeof record.lastmod === 'string' && !Number.isNaN(Date.parse(record.lastmod))));
}
